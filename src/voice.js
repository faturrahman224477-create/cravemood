/* ===== Cimo voice engine — warm pre-rendered voice pack =====
   Every spoken line uses the offline clips generated by tools/gen-voice-edge.py.
   Browser TTS stays disabled: it made Cimo sound stiff and robotic. The clips
   are rendered at a calm conversation tempo and played without pitch shifting.

   audio/cimo/cimo-voice.mp3 is the original Kuon-style reference clip and can
   still be replayed from settings. */

const CIMO_CLIP = 'audio/cimo/cimo-voice.mp3';
/* every Cimo line is pre-rendered — browser TTS is never used at runtime */
const USE_BROWSER_TTS = false;

/* the host gate also guards sub-resources, so carry the share code along */
function assetUrl(path) {
  try {
    const sc = new URLSearchParams(location.search).get('sharecode');
    if (!sc) return path;
    return path + (path.indexOf('?') > -1 ? '&' : '?') + 'sharecode=' + encodeURIComponent(sc);
  } catch (e) { return path; }
}

/* lively but unhurried — inside the 1.05–1.15 / 1.12–1.25 window */
const BASE_RATE = 1.09;
const BASE_PITCH = 1.18;
const RATE_MIN = 1.05, RATE_MAX = 1.15;
const PITCH_MIN = 1.12, PITCH_MAX = 1.25;
const clamp = (v, lo, hi) => Math.max(lo, Math.min(hi, v));
/* small mood colouring; every value still lands inside the global window */
const MOODTONE = {
  senang:  { r: 1.03, p: 1.04, gap: 65 },
  sedih:   { r: 0.97, p: 0.98, gap: 95 },
  marah:   { r: 1.02, p: 1.00, gap: 60 },
  bingung: { r: 1.00, p: 1.02, gap: 80 },
  capek:   { r: 0.97, p: 0.98, gap: 95 },
  kecewa:  { r: 0.98, p: 0.98, gap: 90 },
  def:     { r: 1.00, p: 1.00, gap: 70 },
};
/* fallback lines for canned keys when a caller does not provide text */
const FIXED_TEXT = {
  greet: 'Hai, aku Cimo! Lagi mood apa hari ini?',
  preview: 'Hai, aku Cimo! Kalau kamu lagi capek, cerita aja. Aku dengerin sampai selesai, ya.',
  added: 'Sudah masuk keranjang, nih!',
  saved: 'Sudah tersimpan, ya.',
  home: 'Hai, aku Cimo! Yuk, cek rekomendasi makanan buat kamu.',
  intro: 'Hai, aku Cimo! Temanmu yang suka nyari makanan sesuai mood kamu.',
};

const Voice = (() => {
  const synth = window.speechSynthesis || null;
  const LOCALE = { id: 'id-ID', en: 'en-US', zh: 'zh-CN', hi: 'hi-IN' };
  let voices = [], enabled = true, volume = 1, speaking = false, token = 0, currentAudio = null;
  let actx = null, currentSource = null, irBuffer = null;
  const bufferCache = new Map();
  const S = { lang: 'id', name: '' };

  /* ---- reference voice profile -------------------------------------
     the owner's recording is analysed once (median pitch + syllable rate)
     so the spoken voice sits in the same register and tempo as the clip */
  const REF = { pitch: 1, rate: 1, f0: 0, syl: 0, ready: false };
  let refLoading = null;
  /* the analysis is cheap but not instant — remember it after the first run */
  const REF_KEY = 'cm_voice_ref_v2';
  try {
    const c = JSON.parse(localStorage.getItem(REF_KEY) || 'null');
    if (c && c.f0) { REF.pitch = c.pitch; REF.rate = c.rate; REF.f0 = c.f0; REF.syl = c.syl; REF.ready = true; }
  } catch (e) {}

  function analyse(buffer) {
    try {
      const sr = buffer.sampleRate;
      const raw = buffer.getChannelData(0);
      const step = Math.max(1, Math.floor(sr / 8000));
      const n = Math.floor(raw.length / step);
      const x = new Float32Array(n);
      for (let i = 0; i < n; i++) x[i] = raw[i * step];
      const asr = sr / step;
      const frame = Math.floor(asr * 0.04);
      const hop = Math.floor(asr * 0.02);
      const minLag = Math.floor(asr / 400), maxLag = Math.floor(asr / 70);
      const f0s = [];
      let peaks = 0, prevLoud = false;
      for (let s = 0; s + frame < n; s += hop) {
        let e = 0;
        for (let i = 0; i < frame; i++) { const v = x[s + i]; e += v * v; }
        const rms = Math.sqrt(e / frame);
        if (rms > 0.02) {
          let best = 0, bestLag = 0;
          for (let lag = minLag; lag <= maxLag; lag++) {
            let sum = 0;
            for (let i = 0; i < frame - lag; i++) sum += x[s + i] * x[s + i + lag];
            if (sum > best) { best = sum; bestLag = lag; }
          }
          if (bestLag) { const hz = asr / bestLag; if (hz > 70 && hz < 400) f0s.push(hz); }
        }
        const loud = rms > 0.05;
        if (loud && !prevLoud) peaks++;
        prevLoud = loud;
      }
      f0s.sort((a, b) => a - b);
      const f0 = f0s.length ? f0s[Math.floor(f0s.length / 2)] : 0;
      const dur = buffer.duration || 1;
      return { f0, syl: peaks / dur };
    } catch (e) { return { f0: 0, syl: 0 }; }
  }

  function loadRef() {
    if (refLoading) return refLoading;
    refLoading = (async () => {
      try {
        const res = await fetch(assetUrl(CIMO_CLIP), { cache: 'no-cache' });
        if (!res.ok) return;
        const ab = await res.arrayBuffer();
        const C = window.AudioContext || window.webkitAudioContext;
        if (!C) return;
        const c = new C();
        const buf = await c.decodeAudioData(ab);
        const r = analyse(buf);
        /* reference only — the spoken voice stays inside the global window */
        if (r.f0) REF.pitch = clamp(r.f0 / 205, PITCH_MIN, PITCH_MAX);
        if (r.syl) REF.rate = clamp(r.syl / 4.2, RATE_MIN, RATE_MAX);
        REF.f0 = Math.round(r.f0); REF.syl = +r.syl.toFixed(2); REF.ready = true;
        try { localStorage.setItem(REF_KEY, JSON.stringify({ pitch: REF.pitch, rate: REF.rate, f0: REF.f0, syl: REF.syl })); } catch (e) {}
        try { c.close(); } catch (e) {}
      } catch (e) {}
    })();
    return refLoading;
  }
  loadRef();

  function loadVoices() {
    if (!synth) return;
    try { voices = synth.getVoices() || []; } catch (e) { voices = []; }
  }
  if (synth) {
    loadVoices();
    if (synth.addEventListener) synth.addEventListener('voiceschanged', loadVoices);
    synth.onvoiceschanged = loadVoices;
    setTimeout(loadVoices, 400);
    setTimeout(loadVoices, 1500);
  }

  const HUMAN = /natural|neural|online|premium|enhanced|siri|expressive/i;
  const NICE = /gadis|andika|ardi|damayanti|siti|swara|dewi|indah|xiaoxiao|aria|jenny|kalpana|heera|zira|samantha/i;

  function score(v, lang) {
    const want = (LOCALE[lang] || 'id-ID').toLowerCase();
    const pre = want.split('-')[0];
    const n = (v.name || '').toLowerCase();
    const l = (v.lang || '').toLowerCase().replace('_', '-');
    let s = 0;
    if (l === want) s += 60; else if (l.startsWith(pre)) s += 35; else return -1;
    if (HUMAN.test(n)) s += 40;
    if (NICE.test(n)) s += 18;
    if (/google/.test(n)) s += 12;
    if (/microsoft/.test(n)) s += 6;
    if (/female|wanita|perempuan/.test(n)) s += 6;
    if (v.localService) s += 3;
    return s;
  }

  function pickVoice(lang) {
    let best = null, bs = -1;
    for (const v of voices) {
      const s = score(v, lang || S.lang);
      if (s > bs) { bs = s; best = v; }
    }
    return best;
  }

  /* optional exact recordings: { "normalised text": "file.mp3" } */
  let pack = null;
  /* the ElevenLabs voice pack (generated by tools/gen-voice.mjs) */
  let lines = null;
  function packKey(t) {
    return String(t).toLowerCase().replace(/[^\p{L}\p{N}\s]/gu, ' ').replace(/\s+/g, ' ').trim();
  }
  /* the recordings never contain the user's name — look the line up without it
     (mirrors the same cleanup in tools/gen-chat.mjs) */
  function stripName(t) {
    if (!S.name) return t;
    const n = String(S.name).replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    let s = String(t);
    if (new RegExp('^\\s*' + n, 'i').test(s)) {
      s = s.replace(new RegExp('^\\s*' + n + '\\s*[!,.?]?\\s*', 'i'), '');
    } else {
      s = s.replace(new RegExp(n + '\\s*!', 'gi'), '!')
           .replace(new RegExp(',\\s*' + n, 'gi'), '')
           .replace(new RegExp(n + ',\\s*', 'gi'), '')
           .replace(new RegExp(n, 'gi'), 'kamu');
    }
    return s.replace(/\s+([!?.,])/g, '$1').replace(/\s+/g, ' ').trim();
  }
  /* token overlap so small wording differences still reach the real recording
     (never below 0.86 — we must not speak a different sentence) */
  function nearKey(text) {
    if (!pack) return null;
    const raw = packKey(text);
    const toks = raw.split(' ').filter(w => w.length > 2);
    if (toks.length < 3) return null;
    const set = new Set(toks);
    let best = null, bestScore = 0;
    for (const k in pack) {
      const kt = k.split(' ').filter(w => w.length > 2);
      if (Math.abs(kt.length - toks.length) > 2) continue;
      const ks = new Set(kt);
      let hit = 0;
      for (const w of set) if (ks.has(w)) hit++;
      const score = (2 * hit) / (set.size + ks.size);
      if (score > bestScore) { bestScore = score; best = k; }
    }
    return bestScore >= 0.86 && best ? pack[best] : null;
  }
  function lookup(text) {
    if (!pack) return null;
    return pack[packKey(text)] || (S.name ? pack[packKey(stripName(text))] : null) || nearKey(text) || null;
  }
  let packDone = null;
  function loadPack() {
    if (packDone) return packDone;
    if (!(typeof fetch === 'function' && /^https?:$/.test(location.protocol))) { packDone = Promise.resolve(); return packDone; }
    packDone = fetch(assetUrl('audio/cimo/manifest.json'), { cache: 'no-cache' })
      .then(r => (r.ok ? r.json() : null))
      .then(j => { if (j && typeof j === 'object') pack = j; })
      .catch(() => {});
    return packDone;
  }
  loadPack();
  if (typeof fetch === 'function' && /^https?:$/.test(location.protocol)) {
    fetch(assetUrl('audio/cimo/lines.json'), { cache: 'no-cache' })
      .then(r => (r.ok ? r.json() : null))
      .then(j => { if (j && j.moods) lines = j; })
      .catch(() => {});
  }

  /* play at the authored tempo — the old extra speed-up also raised the pitch */
  const CIMO_RATE = 1;

  /* ---- soft playback chain -----------------------------------------
     Light smoothing only: a gentle 12 kHz low-pass, a very small presence
     lift, longer edge fades and a short room reverb. No tempo or pitch shift. */
  function audioCtx() {
    if (!actx) {
      const C = window.AudioContext || window.webkitAudioContext;
      if (!C) return null;
      try { actx = new C(); } catch (e) { return null; }
    }
    if (actx.state === 'suspended') { try { actx.resume(); } catch (e) {} }
    return actx;
  }
  function shortIR(c) {
    if (irBuffer) return irBuffer;
    const len = Math.floor(c.sampleRate * 0.22);
    const b = c.createBuffer(2, len, c.sampleRate);
    for (let ch = 0; ch < 2; ch++) {
      const d = b.getChannelData(ch);
      for (let i = 0; i < len; i++) d[i] = (Math.random() * 2 - 1) * Math.pow(1 - i / len, 2.8);
    }
    irBuffer = b;
    return b;
  }
  /* clips keep their filenames across regenerations — always revalidate,
     otherwise the browser keeps playing the old voice from disk cache */
  async function decoded(path) {
    if (bufferCache.has(path)) return bufferCache.get(path);
    const c = audioCtx(); if (!c) return null;
    const res = await fetch(assetUrl(path), { cache: 'no-cache' });
    if (!res.ok) return null;
    const buf = await c.decodeAudioData(await res.arrayBuffer());
    bufferCache.set(path, buf);
    return buf;
  }
  function playSoft(path, rate) {
    const myToken = token;
    return new Promise(resolve => {
      let done = false;
      const fin = v => { if (!done) { done = true; resolve(v); } };
      (async () => {
        const c = audioCtx(); if (!c) return fin(false);
        const buf = await decoded(path); if (!buf || myToken !== token) return fin(false);
        const rt = rate || 1;
        /* trim only real silence, with a little breathing room at both ends */
        const raw = buf.getChannelData(0);
        const step = Math.max(1, Math.floor(raw.length / 8000));
        let first = 0, last = raw.length - 1;
        while (first < raw.length && Math.abs(raw[first]) < 0.008) first += step;
        while (last > first && Math.abs(raw[last]) < 0.008) last -= step;
        const offset = Math.max(0, first / buf.sampleRate - 0.03);
        const end = Math.min(buf.duration, last / buf.sampleRate + 0.04);
        const span = Math.max(0.25, end - offset);

        const src = c.createBufferSource();
        src.buffer = buf; src.playbackRate.value = rt;
        const lp = c.createBiquadFilter(); lp.type = 'lowpass'; lp.frequency.value = 12000;
        const pk = c.createBiquadFilter(); pk.type = 'peaking'; pk.frequency.value = 2800; pk.Q.value = 0.9; pk.gain.value = 0.6;
        const env = c.createGain();
        const wet = c.createGain(); wet.gain.value = 0.02;
        const conv = c.createConvolver(); conv.buffer = shortIR(c);
        const t = c.currentTime + 0.015;
        const total = span / rt;
        const top = Math.max(0.0001, Math.min(1, volume) * 0.95);
        env.gain.setValueAtTime(0.0001, t);
        env.gain.linearRampToValueAtTime(top, t + 0.035);
        env.gain.setValueAtTime(top, t + Math.max(0.08, total - 0.075));
        env.gain.linearRampToValueAtTime(0.0001, t + total);
        src.connect(lp); lp.connect(pk); pk.connect(env);
        env.connect(c.destination);
        env.connect(wet); wet.connect(conv); conv.connect(c.destination);
        currentSource = src;
        speaking = true;
        src.onended = () => { if (currentSource === src) currentSource = null; fin(true); };
        src.start(t, offset, span); src.stop(t + total + 0.02);
        setTimeout(() => fin(true), (total + 0.7) * 1000);
      })().catch(() => fin(false));
    });
  }
  /* plain <audio> — kept as a fallback for browsers without Web Audio */
  function playHtml(path, rate) {
    return new Promise(resolve => {
      let done = false;
      const fin = v => { if (!done) { done = true; resolve(v); } };
      try {
        const a = new Audio(assetUrl(path));
        currentAudio = a;
        a.volume = Math.max(0, Math.min(1, volume));
        const rt = rate || 1;
        if (rt !== 1) {
          a.playbackRate = rt;
          try { a.preservesPitch = false; } catch (e) {}
          try { a.webkitPreservesPitch = false; } catch (e) {}
        }
        a.onended = () => { if (currentAudio === a) currentAudio = null; fin(true); };
        a.onerror = () => fin(false);
        a.onloadedmetadata = () => {
          const d = isFinite(a.duration) ? a.duration : 3;
          setTimeout(() => fin(true), (d / rt) * 1000 + 700);
        };
        a.play().then(() => { speaking = true; }).catch(() => fin(false));
        setTimeout(() => fin(true), 20000);
      } catch (e) { fin(false); }
    });
  }
  function playFile(path, rate) {
    return playSoft(path, rate).then(ok => ok ? true : playHtml(path, rate));
  }
  function playClip(file) { return playFile('audio/cimo/' + file, CIMO_RATE); }

  /* ---- automatic text cleanup -------------------------------------
     emoji, markdown and odd symbols are removed before the text ever
     reaches speechSynthesis, so nothing is read out as "star" or "backtick". */
  function cleanSpeech(text) {
    let s = String(text == null ? '' : text);
    s = s.replace(/https?:\/\/\S+/g, ' ')
         .replace(/[\u{1F000}-\u{1FAFF}\u{2600}-\u{27BF}\u{FE0F}\u{2190}-\u{21FF}\u{2B00}-\u{2BFF}]/gu, ' ')
         .replace(/[*_`~#>\\[\]{}|]/g, ' ')
         .replace(/\s*\n+\s*/g, ' ')
         .replace(/[ \t]{2,}/g, ' ')
         .replace(/\s+([,!?.;:])/g, '$1')
         .replace(/[,]{2,}/g, ',')
         .replace(/\s{2,}/g, ' ')
         .trim();
    /* a tiny pause after the friendly greeting keeps it lively */
    if (/^hai(?=\s+[A-Za-z])/i.test(s)) s = s.replace(/^hai/i, 'Hai,');
    return s;
  }
  /* Natural rhythm: short phrases at commas / full stops / exclamations.
     Very short fragments are merged back so it never sounds clipped. */
  function chunks(text) {
    const clean = cleanSpeech(text);
    if (!clean) return [];
    const parts = clean.split(/(?<=[,!?.;:])\s+/).map(s => s.trim()).filter(Boolean);
    const out = [];
    for (const part of parts) {
      if (part.length > 110) {
        let cur = '';
        for (const w of part.split(/\s+/)) {
          if ((cur + ' ' + w).trim().length > 90) { if (cur) out.push(cur); cur = w; }
          else cur = (cur ? cur + ' ' : '') + w;
        }
        if (cur) out.push(cur);
      } else if (out.length && part.length < 10) {
        out[out.length - 1] += ' ' + part;
      } else out.push(part);
    }
    return out;
  }

  function stop() {
    token++;
    if (currentAudio) { try { currentAudio.pause(); } catch (e) {} currentAudio = null; }
    if (currentSource) { try { currentSource.stop(); } catch (e) {} currentSource = null; }
    if (synth) { try { synth.cancel(); } catch (e) {} }
    speaking = false;
  }

  /* Global speak: every Cimo line in the app ends up here.
     A natural pre-rendered clip wins when the line exists — browser TTS
     cannot reproduce Cimo's actual voice. Browser speech is the silent
     fallback for lines that were never recorded. */
  async function speak(text, opts) {
    opts = opts || {};
    if (!enabled) return;
    const clean = cleanSpeech(text);
    if (!clean) return;

    if (!pack) await loadPack();
    const clip = lookup(text) || lookup(clean);
    if (clip) { stop(); return playClip(clip); }
    /* no recording for this line: stay silent instead of dropping into the
       stiff browser voice — the pack is meant to be the only spoken voice */
    if (!synth || !USE_BROWSER_TTS) return;

    const list = chunks(clean);
    if (!list.length) return;

    /* cancel the old queue before starting a new line — instant, smooth replies */
    stop();
    const my = token;
    const v = pickVoice(opts.lang || S.lang);
    const tone = MOODTONE[opts.mood] || MOODTONE.def;
    const rate = clamp(BASE_RATE * tone.r * (opts.rate || 1), RATE_MIN, RATE_MAX);
    const pitch = clamp(BASE_PITCH * tone.p * (opts.pitch || 1), PITCH_MIN, PITCH_MAX);
    speaking = true;

    return new Promise(resolve => {
      let i = 0, finished = false;
      const done = () => {
        if (finished) return;
        finished = true;
        if (my === token) speaking = false;
        resolve();
      };
      const next = () => {
        if (finished || my !== token) return done();
        if (i >= list.length) return done();
        const seg = list[i++];
        try {
          const u = new SpeechSynthesisUtterance(seg);
          if (v) { u.voice = v; u.lang = v.lang; }
          else u.lang = LOCALE[opts.lang || S.lang] || 'id-ID';
          const isQ = /[?？]$/.test(seg);
          u.rate = clamp(rate, RATE_MIN, RATE_MAX);
          u.pitch = clamp(pitch + (isQ ? 0.02 : 0), PITCH_MIN, PITCH_MAX);
          u.volume = clamp(volume, 0, 1);
          u.onend = () => setTimeout(next, i >= list.length ? 0 : tone.gap);
          u.onerror = () => done();          /* audio permission / engine errors stay silent */
          synth.speak(u);
        } catch (e) { done(); }
      };
      next();
      /* safety net: some engines never fire onend */
      const guard = setInterval(() => {
        if (finished || my !== token) { clearInterval(guard); return; }
        if (i >= list.length && !synth.speaking && !synth.pending) { clearInterval(guard); done(); }
      }, 800);
    });
  }

  return {
    get supported() { return !!synth; },
    get hasPack() { return !!(lines && lines.moods); },
    /* mood recommendation — natural recording first, browser TTS fallback */
    async speakMood(mood, dishId, fallbackText) {
      if (!enabled) return;
      if (lines && lines.moods && lines.moods[mood]) {
        const mm = lines.moods[mood], segs = [];
        if (mm.pre) segs.push(mm.pre);
        if (dishId && lines.dishes && lines.dishes[dishId]) segs.push(lines.dishes[dishId]);
        if (mm.post) segs.push(mm.post);
        if (segs.length) {
          stop();
          const my = token;
          speaking = true;
          for (let i = 0; i < segs.length; i++) {
            if (my !== token || !enabled) break;
            await playClip(segs[i]);
            /* a soft breath between recommendation parts, like a real reply */
            if (my === token && i < segs.length - 1) await new Promise(r => setTimeout(r, 130));
          }
          if (my === token) speaking = false;
          return;
        }
      }
      return speak(fallbackText || FIXED_TEXT.greet, { mood });
    },
    /* greeting / preview / added / saved / intro — same natural voice pack */
    async speakFixed(key, fallbackText, opts) {
      if (!enabled) return;
      const f = lines && lines.fixed && lines.fixed[key];
      if (f) {
        stop();
        const my = token;
        speaking = true;
        await playClip(f);
        if (my === token) speaking = false;
        return;
      }
      return speak(fallbackText || FIXED_TEXT[key] || FIXED_TEXT.greet, opts);
    },
    get ready() { return !!synth && voices.length > 0; },
    get speaking() { return speaking; },
    get enabled() { return enabled; },
    set enabled(v) { enabled = !!v; if (!v) stop(); },
    get volume() { return volume; },
    set volume(v) { volume = Math.max(0, Math.min(1, v)); },
    get settings() { return { enabled, volume, lang: S.lang, name: S.name, ref: REF }; },
    set(k, v) { if (k === 'volume') volume = v; else if (k === 'enabled') enabled = !!v; else if (k === 'lang') S.lang = v; else if (k === 'name') S.name = v || ''; },
    setAll(o) { if (!o) return; if ('volume' in o) volume = o.volume; if ('enabled' in o) enabled = o.enabled; if ('lang' in o && o.lang) S.lang = o.lang; if ('name' in o) S.name = o.name || ''; },
    stop, speak,
    _lookup(t) { return lookup(t); },
    playOriginal() { return playFile(CIMO_CLIP); },
    preview() {
      return this.speakFixed('preview', 'Hai, aku Cimo. Kalau kamu lagi capek, cerita aja. Aku dengerin sampai selesai.', { mood: 'def' });
    },
  };
})();

/* ===== synthesized UI sounds (no assets needed) ===== */
const SFX = (() => {
  let ctx = null, on = true, tickToken = 0;
  function ac() {
    if (!ctx) {
      const C = window.AudioContext || window.webkitAudioContext;
      if (!C) return null;
      ctx = new C();
    }
    if (ctx.state === 'suspended') ctx.resume();
    return ctx;
  }
  function tone(freq, dur, type, gain, slideTo, delay) {
    const c = ac(); if (!c) return;
    const t0 = c.currentTime + (delay || 0);
    const o = c.createOscillator(), g = c.createGain();
    o.type = type || 'sine';
    o.frequency.setValueAtTime(freq, t0);
    if (slideTo) o.frequency.exponentialRampToValueAtTime(slideTo, t0 + dur);
    g.gain.setValueAtTime(0.0001, t0);
    g.gain.exponentialRampToValueAtTime(gain || 0.16, t0 + 0.012);
    g.gain.exponentialRampToValueAtTime(0.0001, t0 + dur);
    o.connect(g); g.connect(c.destination);
    o.start(t0); o.stop(t0 + dur + 0.02);
  }
  const lib = {
    add() { tone(660, .09, 'triangle', .16, 1180); setTimeout(() => tone(1320, .07, 'sine', .09), 55); },
    remove() { tone(420, .1, 'triangle', .13, 260); },
    /* happy little two-note pluck: G5 → C6 + a soft E6 sparkle */
    tap() { tone(784, .055, 'triangle', .075, 1046); tone(1318, .05, 'sine', .032, null, .028); },
    pop() { tone(520, .07, 'sine', .12, 900); },
    success() { [523, 659, 784, 1046].forEach((f, i) => setTimeout(() => tone(f, .16, 'sine', .11), i * 80)); },
    tick() { tone(1400, .03, 'square', .05); },
    error() { tone(240, .18, 'sawtooth', .09, 160); },
    spin() { for (let i = 0; i < 8; i++) setTimeout(() => tone(900 - i * 60, .04, 'square', .04), i * 55); },
  };
  return {
    get enabled() { return on; },
    set enabled(v) { on = !!v; },
    init() { ac(); },
    play(name) { if (!on) return; try { (lib[name] || lib.tap)(); } catch (e) {} },
    /* ticks that slow down with the wheel — feels like it is really spinning */
    spinTicks(dur) {
      if (!on) return;
      const token = ++tickToken;
      const total = dur || 3800;
      const t0 = performance.now();
      const step = () => {
        if (token !== tickToken) return;
        const p = Math.min(1, (performance.now() - t0) / total);
        if (p >= 1) return;
        tone(1500 - p * 780, 0.028, 'square', Math.max(0.018, 0.055 - p * 0.03));
        setTimeout(step, 42 + 300 * Math.pow(p, 2.4));
      };
      step();
    },
    stopTicks() { tickToken++; },
  };
})();
